// `node scripts/update-reference-data.mjs`: refreshes the copies of public reference data that
// the services ship with (docs/07 §3). The app never calls these APIs while it runs, so it keeps
// working when they are down; run this when banks or administrative units change, review the
// diff, commit it.
//   - Banks (NAPAS BIN): https://api.vietqr.io/v2/banks → billing-service
//   - Provinces and wards after the 2025 reform (34 provinces, no districts):
//     https://provinces.open-api.vn/api/v2 → tutor-service
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const get = async (url) => {
  const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.json();
};
const fail = (what) => {
  throw new Error(`unexpected data: ${what}`);
};
const str = (v, max = 200) =>
  typeof v === 'string' && v.trim() && v.length <= max ? v.trim() : fail(JSON.stringify(v));
const int = (v) => (Number.isInteger(v) && v > 0 ? v : fail(JSON.stringify(v)));

const banks = (await get('https://api.vietqr.io/v2/banks')).data
  .map((b) => ({
    bin: /^\d{6}$/.test(b.bin) ? b.bin : fail(`bin ${b.bin}`),
    code: str(b.code, 20),
    shortName: str(b.shortName, 60),
    name: str(b.name),
    transfer: b.transferSupported === 1,
  }))
  .sort((a, b) => a.shortName.localeCompare(b.shortName, 'vi'));

const provinces = (await get('https://provinces.open-api.vn/api/v2/p/'))
  .map((p) => [int(p.code), str(p.name)])
  .sort((a, b) => a[0] - b[0]);
const known = new Set(provinces.map(([code]) => code));
const wards = (await get('https://provinces.open-api.vn/api/v2/w/'))
  .map((w) => [
    int(w.code),
    str(w.name),
    known.has(w.province_code) ? w.province_code : fail(w.code),
  ])
  .sort((a, b) => a[0] - b[0]);
for (const [list, what] of [
  [banks.map((b) => b.bin), 'bank BIN'],
  [wards.map((w) => w[0]), 'ward code'],
]) {
  if (new Set(list).size !== list.length) fail(`duplicate ${what}`);
}

const header = (source) =>
  `// Generated by scripts/update-reference-data.mjs from ${source} on ${new Date()
    .toISOString()
    .slice(0, 10)}. Do not edit by hand.\n`;
writeFileSync(
  join(root, 'backend/billing-service/src/bank/vn-banks.ts'),
  `${header('api.vietqr.io')}export const VN_BANKS = ${JSON.stringify(banks)} as const;\n`,
);
writeFileSync(
  join(root, 'backend/tutor-service/src/locations/vn-locations.ts'),
  `${header('provinces.open-api.vn v2')}/** [code, name] */\nexport const PROVINCES: readonly (readonly [number, string])[] = ${JSON.stringify(provinces)};\n/** [code, name, provinceCode] */\nexport const WARDS: readonly (readonly [number, string, number])[] = ${JSON.stringify(wards)};\n`,
);
console.log(`${banks.length} banks, ${provinces.length} provinces, ${wards.length} wards`);
